"""Sandboxed execution of *public* contract examples.

Worker deliverables are untrusted code, so nothing here imports or calls them on the host. A fresh,
network-disabled, throwaway sandbox is created for the verification, the exported snapshot is
uploaded, and a Host-authored test file runs the published examples. The sandbox is destroyed even
when the run fails.

The sandbox is independent from the worker sandbox: it is created after the workspace export, has
its own id, mounts no worker secret reference and never writes back to the exported workspace.
"""

from __future__ import annotations

import asyncio
import contextlib
import re
import time
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from anycode.sandbox import SandboxCommand, SandboxProvider, SandboxSpec

from atlasos.verification import models

_MAX_FILES = 400
_MAX_FILE_BYTES = 2_000_000
_SKIP_PARTS = frozenset({".git", "__pycache__", ".pytest_cache", ".venv", "node_modules"})


@dataclass(frozen=True)
class DynamicOutcome:
    status: models.Status
    reason_code: str
    detail: str = ""
    sandbox_id: str | None = None
    wall_ms: float | None = None


def _header(case: Mapping[str, Any]) -> str:
    imports = ", ".join(str(item) for item in case.get("imports") or [])
    module = str(case.get("module") or "")
    return f"from {module} import {imports}" if module else ""


def render_public_tests(cases: Sequence[Mapping[str, Any]]) -> tuple[str, dict[str, str]]:
    """Render the Host-authored test module and a case-id map.

    Every case is one function so a failure names exactly one published rule.
    """

    lines = [
        '"""Public contract checks generated by AtlasRuntime verification (trusted spec)."""',
        "import pytest",
        "",
    ]
    names: dict[str, str] = {}
    for index, case in enumerate(cases):
        name = f"test_case_{index:02d}"
        names[name] = str(case.get("case_id") or name)
        lines.append("")
        lines.append(f"def {name}() -> None:")
        header = _header(case)
        if header:
            lines.append(f"    {header}")
        code = str(case.get("code") or "")
        raises = case.get("raises")
        if raises:
            lines.append(f"    with pytest.raises({raises}):")
            lines.append(f"        {code}")
        else:
            lines.append(f"    actual = {code}")
            lines.append(f"    expected = {case.get('expected_literal')!r}")
            lines.append("    assert actual == expected, (actual, expected)")
    lines.append("")
    return "\n".join(lines), names


def parse_pytest_failure(stdout: str, names: Mapping[str, str]) -> str:
    """Map ``FAILED file::test_case_01`` markers back to published case ids.

    The sandbox transport can return the whole stdout as a single line, so the marker is searched
    for anywhere in the text instead of at a line start.
    """

    failed: list[str] = []
    for match in re.finditer(r"FAILED\s+\S*::(\w+)", stdout):
        function = match.group(1)
        failed.append(names.get(function, function))
    return ", ".join(sorted(set(failed)))


class SandboxContractRunner:
    """Runs published examples inside a disposable sandbox."""

    def __init__(
        self,
        provider: SandboxProvider,
        *,
        image: str | None,
        workspace: str = "/workspace/verify",
        timeout_seconds: int = 180,
        run_id: str = "verification",
    ) -> None:
        self.provider = provider
        self.image = image
        self.workspace = workspace
        self.timeout_seconds = timeout_seconds
        self.run_id = run_id

    async def run(self, *, snapshot: Path, cases: Sequence[Mapping[str, Any]]) -> DynamicOutcome:
        started = time.perf_counter()
        if not cases:
            return DynamicOutcome("NOT_APPLICABLE", models.REASON_UNSUPPORTED, "no dynamic cases")
        module, names = render_public_tests(cases)
        spec = SandboxSpec(
            run_id=f"{self.run_id}-verify",
            task_id="verification",
            correlation_id=f"{self.run_id}:verification",
            context=_verification_context(),
            image=self.image,
            network="none",
            persistent=False,
            labels={"atlas_verification": "1"},
        )
        handle_id: str | None = None
        provider = self.provider
        try:
            created = await provider.create(spec)
        except Exception as error:  # noqa: BLE001 - any provider failure is UNKNOWN, not FAIL
            return DynamicOutcome(
                "UNKNOWN",
                models.REASON_DYNAMIC_ERROR,
                f"sandbox creation failed: {type(error).__name__}: {error}",
                wall_ms=_elapsed(started),
            )
        if not created.ok or created.handle is None:
            return DynamicOutcome(
                "UNKNOWN",
                models.REASON_DYNAMIC_ERROR,
                f"sandbox creation refused: {created.error}",
                wall_ms=_elapsed(started),
            )
        handle = created.handle
        handle_id = handle.id
        try:
            prepared = await self._upload(snapshot, module, handle)
            if prepared is not None:
                return DynamicOutcome(
                    "UNKNOWN",
                    models.REASON_DYNAMIC_ERROR,
                    prepared,
                    handle_id,
                    _elapsed(started),
                )
            result = await provider.execute(
                handle,
                SandboxCommand(
                    command="python3 -m pytest -q --tb=no -rf test_public_contract.py",
                    cwd=self.workspace,
                    timeout_seconds=self.timeout_seconds,
                ),
            )
        except TimeoutError:
            return DynamicOutcome(
                "UNKNOWN",
                models.REASON_DYNAMIC_TIMEOUT,
                "public contract execution timed out",
                handle_id,
                _elapsed(started),
            )
        except Exception as error:  # noqa: BLE001
            return DynamicOutcome(
                "UNKNOWN",
                models.REASON_DYNAMIC_ERROR,
                f"{type(error).__name__}: {error}",
                handle_id,
                _elapsed(started),
            )
        finally:
            if handle_id is not None:
                with contextlib.suppress(Exception):
                    await provider.destroy(handle)
        detail = (result.stdout or "") + (result.stderr or "")
        if result.exit_code == 0:
            return DynamicOutcome(
                "PASS", models.REASON_OK, detail[-2000:], handle_id, _elapsed(started)
            )
        if result.exit_code == 1:
            failed = parse_pytest_failure(result.stdout or "", names)
            return DynamicOutcome(
                "FAIL",
                models.REASON_SHAPE_MISMATCH,
                f"failing public rule(s): {failed}" if failed else detail[-2000:],
                handle_id,
                _elapsed(started),
            )
        return DynamicOutcome(
            "UNKNOWN",
            models.REASON_DYNAMIC_ERROR,
            f"pytest exit code {result.exit_code}: {detail[-1500:]}",
            handle_id,
            _elapsed(started),
        )

    async def _upload(self, snapshot: Path, module: str, handle: Any) -> str | None:
        payload, problem = await asyncio.to_thread(_collect_files, snapshot)
        if problem is not None:
            return problem
        for relative, data in payload:
            target = f"{self.workspace}/{relative}"
            written = await self.provider.write_file(handle, target, data)
            if not written.ok:
                return f"upload of {relative} failed: {written.error}"
        test_path = f"{self.workspace}/test_public_contract.py"
        written = await self.provider.write_file(handle, test_path, module.encode("utf-8"))
        if not written.ok:
            return f"upload of the public contract tests failed: {written.error}"
        return None


def _collect_files(snapshot: Path) -> tuple[list[tuple[str, bytes]], str | None]:
    """Read the export to upload, refusing an oversized tree.

    Runs in a worker thread: the async caller never touches the filesystem directly.
    """

    payload: list[tuple[str, bytes]] = []
    for item in sorted(snapshot.rglob("*")):
        if not item.is_file() or item.is_symlink():
            continue
        relative = item.relative_to(snapshot).as_posix()
        if _SKIP_PARTS.intersection(relative.split("/")) or relative.startswith("."):
            continue
        data = item.read_bytes()
        if len(data) > _MAX_FILE_BYTES:
            return [], f"artifact {relative} exceeds the verification upload limit"
        payload.append((relative, data))
        if len(payload) > _MAX_FILES:
            return [], "artifact tree exceeds the verification file limit"
    return payload, None


def _verification_context() -> Any:
    from anycode.identity import ExecutionContext

    return ExecutionContext(
        principal="system:verification",
        tenant_scope="atlas-verification",
        classification="internal",
        attributes={"run_id": "verification"},
    )


def _elapsed(started: float) -> float:
    return round((time.perf_counter() - started) * 1000.0, 3)


